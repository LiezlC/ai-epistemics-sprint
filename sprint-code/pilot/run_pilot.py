"""Run the non-scored pilot through one model and summarise the headroom (sprint code, 13 Nov 2026).

Reuses the PREEXISTING `con-artist/providers.py` unchanged (see pilot_providers.py). The parse rule, decoding and
thinking setting are the ones proposed in the freeze-note template (pending the user's final confirmation).

  parse rule: take the first {...} JSON object in the answer; if none parses, the answer is "unparseable", scored as
              incorrect and counted separately from wrong verdicts. Verdict must be independent | shared | undetermined.
  decoding:   temperature 0, fixed seed, thinking off (reasoning tokens are recorded so "off" can be checked)

Usage:
  python -I run_pilot.py --packets pilot_packets.jsonl --model qwen/qwen3.8-max-0902 --out RUN_DIR \
        [--route openrouter_chat|fake] [--spend-cap 1.0] [--limit N] [--thinking off|default] [--seed 20261113]

Prints only counts and cost; keys are never read here (OPENROUTER_API_KEY is read inside pilot_providers).
No scored file is read: the packets file is generated by make_pilot_set.py.
"""
from __future__ import annotations

import argparse
import asyncio
import json
import os
import re
import sys
from collections import defaultdict

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from pilot_providers import SprintProviders, SpendCapReached  # noqa: E402

VERDICTS = {"independent", "shared", "undetermined"}


def parse(text):
    """First {...} object that parses as JSON with a valid verdict. Returns (verdict, roots) or None."""
    dec = json.JSONDecoder()
    for m in re.finditer(r"\{", text or ""):
        try:
            obj, _ = dec.raw_decode(text[m.start():])
        except ValueError:
            continue
        if isinstance(obj, dict) and obj.get("verdict") in VERDICTS:
            roots = obj.get("root_records")
            return obj["verdict"], sorted(roots) if isinstance(roots, list) else []
    return None


async def run(args, packets):
    fake = None
    if args.route == "fake":
        from fake_model import fake_call as fake  # test double, no network
    prov = SprintProviders(seed=args.seed, thinking=args.thinking, fake=fake, spend_cap=args.spend_cap)
    os.makedirs(args.out, exist_ok=True)
    results = []

    async def one(p):
        try:
            r = await prov.call(args.route, args.model, None, p["prompt"], args.max_tokens, temperature=0)
        except SpendCapReached as e:
            return {**{k: p[k] for k in p if k != "prompt"}, "error": "spend cap: " + str(e)}
        parsed = parse(r.text)
        rec = {k: p[k] for k in p if k != "prompt"}
        rec.update({"answer": r.text, "parsed": parsed is not None, "verdict": parsed[0] if parsed else None,
                    "roots": parsed[1] if parsed else None, "tokens_in": r.tokens_in, "tokens_out": r.tokens_out,
                    "reasoning_tokens": r.reasoning_tokens, "cost_usd": r.cost_usd, "cost_source": r.cost_source,
                    "finish_reason": r.finish_reason, "model_served": r.model_served, "error": r.error,
                    "latency_s": r.latency_s, "ts_utc": r.ts_utc})
        return rec

    results = await asyncio.gather(*[one(p) for p in packets])
    with open(os.path.join(args.out, "results.jsonl"), "w", encoding="utf-8", newline="\n") as f:
        for x in results:
            f.write(json.dumps(x) + "\n")
    return prov, results


def summarise(results):
    g = defaultdict(lambda: defaultdict(int))
    for x in results:
        key = (x["instruction"], x["condition"] if x["direction"] == x["condition"] else x["direction"], x["label_form"])
        c = g[key]
        c["n"] += 1
        if x.get("error"):
            c["errors"] += 1
            continue
        if not x["parsed"]:
            c["unparseable"] += 1
            continue
        c["correct"] += x["verdict"] == x["truth"]
        if x["label"] is not None:
            c["follows_label"] += x["verdict"] == x["label"]
        c["undetermined"] += x["verdict"] == "undetermined"
    return g


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--packets", required=True)
    ap.add_argument("--model", required=True)
    ap.add_argument("--out", required=True)
    ap.add_argument("--route", default="openrouter_chat")
    ap.add_argument("--spend-cap", type=float, default=1.0)
    ap.add_argument("--limit", type=int, default=None)
    ap.add_argument("--max-tokens", type=int, default=200)
    ap.add_argument("--thinking", default="off", choices=["off", "default"])
    ap.add_argument("--seed", type=int, default=20261113)
    args = ap.parse_args()

    packets = [json.loads(l) for l in open(args.packets, encoding="utf-8") if l.strip()]
    if args.limit:
        packets = packets[:args.limit]
    prov, results = asyncio.run(run(args, packets))
    g = summarise(results)
    rt = [x["reasoning_tokens"] for x in results if x.get("reasoning_tokens")]
    summary = {
        "model": args.model, "route": args.route, "thinking": args.thinking, "seed": args.seed, "temperature": 0,
        "calls": prov.calls, "spend_usd": round(prov.spend, 5), "errors": sum(1 for x in results if x.get("error")),
        "calls_with_reasoning_tokens": len(rt), "reasoning_tokens_total": sum(rt),
        "models_served": sorted({x["model_served"] for x in results if x.get("model_served")}),
        "provenance": "reuses con-artist/providers.py (Swarm sprint code, 6 Nov 2026) unchanged; new: pilot_providers.py, run_pilot.py, make_pilot_set.py (13 Nov 2026)",
        "groups": [{"instruction": k[0], "condition_or_direction": k[1], "label_form": k[2], **dict(v)} for k, v in sorted(g.items())],
    }
    json.dump(summary, open(os.path.join(args.out, "summary.json"), "w", encoding="utf-8"), indent=1)
    print(json.dumps({k: v for k, v in summary.items() if k != "groups"}, indent=1))
    print(f"{'instruction':9} {'condition/direction':18} {'label':10} {'n':>3} {'right':>5} {'follow':>6} {'undet':>5} {'unpars':>6} {'err':>3}")
    for r in summary["groups"]:
        print(f"{r['instruction']:9} {r['condition_or_direction']:18} {r['label_form']:10} {r['n']:>3} {r.get('correct',0):>5} "
              f"{r.get('follows_label',0):>6} {r.get('undetermined',0):>5} {r.get('unparseable',0):>6} {r.get('errors',0):>3}")


if __name__ == "__main__":
    main()
